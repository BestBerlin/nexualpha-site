import test from "node:test";
import assert from "node:assert/strict";
import { mkdir, mkdtemp, rm, symlink, writeFile } from "node:fs/promises";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { runProductionPreflight } from "../ops/release/production-preflight.mjs";

const exec = promisify(execFile);
const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const script = path.join(projectRoot, "ops", "release", "production-preflight.mjs");

async function fixture({ buildId = "3.0-test-r25", collectorMode = "single-writer", stateBuildId = buildId } = {}) {
  const dir = await mkdtemp(path.join(os.tmpdir(), "nexu-production-preflight-"));
  const candidateDir = path.join(dir, "candidate");
  const activeDir = path.join(dir, "active");
  const aliasRoot = path.join(dir, "alias");
  const staticAliasPath = path.join(aliasRoot, "public");
  const nginxIncludePath = path.join(dir, "nginx", "nexualpha-upstream.inc");
  const statePath = path.join(dir, "state.json");
  const collectorConfigPath = path.join(dir, "collector.env");
  await mkdir(candidateDir, { recursive: true });
  await mkdir(activeDir, { recursive: true });
  await mkdir(path.dirname(nginxIncludePath), { recursive: true });
  await mkdir(aliasRoot, { recursive: true });
  await writeFile(path.join(candidateDir, "version.json"), `${JSON.stringify({ version: "3.0.0", buildId })}\n`);
  await writeFile(path.join(activeDir, "version.json"), `${JSON.stringify({ version: "3.0.0", buildId: stateBuildId })}\n`);
  await symlink(activeDir, staticAliasPath, "dir");
  await writeFile(nginxIncludePath, [
    "# Generated by NexuAlpha bluegreen-release.mjs; contains no commercial terms.",
    `# buildId=${stateBuildId} version=3.0.0 lane=blue`,
    "set $nexualpha_upstream http://127.0.0.1:18080;",
    "location = /version.json { alias /srv/nexualpha/version.json; }",
    "location /assets/ { alias /srv/nexualpha/assets/; }",
    "location /brands/ { alias /srv/nexualpha/brands/; }",
    "location /fonts/ { alias /srv/nexualpha/fonts/; }",
    "location / { proxy_pass $nexualpha_upstream; }",
    "",
  ].join("\n"));
  await writeFile(statePath, `${JSON.stringify({
    active: { lane: "blue", port: 18080, version: "3.0.0", buildId: stateBuildId, releaseDir: activeDir },
    previous: { lane: "green", port: 18081, version: "3.0.0", buildId: "3.0-previous", releaseDir: path.join(dir, "previous") },
    pending: null,
  })}\n`);
  await writeFile(collectorConfigPath, [
    "CTA_ENVIRONMENT=production",
    "CTA_DATA_FILE=/data/private/nexualpha/cta/production.jsonl",
    "CTA_ORIGIN=https://nexualpha.com",
    "CTA_SINGLE_WRITER=true",
    `CTA_MODE=${collectorMode}`,
    "",
  ].join("\n"));
  return {
    dir,
    buildId,
    candidateDir,
    statePath,
    collectorConfigPath,
    nginxIncludePath,
    staticAliasPath,
    close: () => rm(dir, { recursive: true, force: true }),
  };
}

test("healthy infrastructure still fails closed when protected commercial files differ from the frozen constitution", async () => {
  const f = await fixture();
  try {
    const report = await runProductionPreflight({
      expectedBuildId: f.buildId,
      baseUrl: "https://nexualpha.com",
      projectRoot,
      candidateDir: f.candidateDir,
      statePath: f.statePath,
      collectorConfigPath: f.collectorConfigPath,
      dataPath: f.dir,
      minFreeBytes: 1024,
      minFreePercent: 1,
      nginxIncludePath: f.nginxIncludePath,
      staticAliasPath: f.staticAliasPath,
      commandRunner: fakeDockerPs(),
      statfsImpl: fakeStatfs(),
      httpProbe: fakeHttpProbe({ coreStatus: 200 }),
    });
    assert.equal(report.status, "BLOCKED");
    assert.deepEqual(report.blockers, ["protected-hashes"]);
    assert.ok(report.checks.filter(check=>check.id!=="protected-hashes").every(check=>check.status==="PASS"));
    assert.equal(report.checks.find((check) => check.id === "protected-hashes").status, "BLOCKED");
    assert.equal(report.checks.find((check) => check.id === "cta-invalid-body-proxy-probe").observedStatus, 400);
    assert.equal(report.checks.find((check) => check.id === "containers").restartPolicyOk, true);
  } finally {
    await f.close();
  }
});

test("core origin not configured is reported explicitly without pretending ready", async () => {
  const f = await fixture();
  try {
    const report = await runProductionPreflight({
      expectedBuildId: f.buildId,
      baseUrl: "https://nexualpha.com",
      projectRoot,
      candidateDir: f.candidateDir,
      statePath: f.statePath,
      collectorConfigPath: f.collectorConfigPath,
      dataPath: f.dir,
      minFreeBytes: 1024,
      minFreePercent: 1,
      nginxIncludePath: f.nginxIncludePath,
      staticAliasPath: f.staticAliasPath,
      commandRunner: fakeDockerPs(),
      statfsImpl: fakeStatfs(),
      httpProbe: fakeHttpProbe({ coreStatus: 503, coreReasonCode: "CORE_API_ORIGIN_NOT_CONFIGURED" }),
    });
    const core = report.checks.find((check) => check.id === "core-readiness");
    assert.equal(report.status, "BLOCKED");
    assert.deepEqual(report.blockers, ["protected-hashes"]);
    assert.equal(core.status, "PASS");
    assert.equal(core.coreConfigured, false);
    assert.match(core.note, /explicitly unconfigured/);
  } finally {
    await f.close();
  }
});

test("preflight blocks multi-writer collector config, wrong live mapping and missing restart policy", async () => {
  const f = await fixture({ collectorMode: "multi-writer", stateBuildId: "3.0-wrong-live" });
  try {
    const report = await runProductionPreflight({
      expectedBuildId: f.buildId,
      baseUrl: "https://nexualpha.com",
      projectRoot,
      candidateDir: f.candidateDir,
      statePath: f.statePath,
      collectorConfigPath: f.collectorConfigPath,
      dataPath: f.dir,
      minFreeBytes: 1024,
      minFreePercent: 1,
      nginxIncludePath: f.nginxIncludePath,
      staticAliasPath: f.staticAliasPath,
      commandRunner: fakeDockerPs({ restartPolicy: "no" }),
      statfsImpl: fakeStatfs(),
      httpProbe: fakeHttpProbe({ coreStatus: 200 }),
    });
    assert.equal(report.status, "BLOCKED");
    assert.ok(report.blockers.includes("cta-collector-config"));
    assert.ok(report.blockers.includes("release-state"));
    assert.ok(report.blockers.includes("containers"));
    assert.ok(report.blockers.includes("nginx-mapping"));
  } finally {
    await f.close();
  }
});

test("CLI returns sanitized nonzero JSON when required production inputs are missing", async () => {
  await assert.rejects(
    exec(process.execPath, [
      script,
      "--expected-build-id", "3.0-test-r25",
      "--base-url", "https://nexualpha.com",
      "--candidate-dir", path.join(projectRoot, "missing-candidate"),
    ], { cwd: projectRoot }),
    (error) => {
      assert.notEqual(error.code, 0);
      assert.doesNotMatch(String(error.stderr), /nexu888|11350287|LUCKX/i);
      assert.match(String(error.stderr), /PRODUCTION_PREFLIGHT_ERROR|ENOENT/);
      return true;
    },
  );
});

function fakeHttpProbe({ coreStatus, coreReasonCode = null }) {
  return async ({ method, url }) => {
    if (method === "POST" && url.endsWith("/api/analytics/cta")) return { status: 400, body: null };
    if (url.endsWith("/api/v1/health/ready")) {
      if (coreStatus === 200) return { status: 200, body: { status: "ready", dependencies: { core: { ready: true } } } };
      return { status: coreStatus, body: { status: "degraded", reasonCode: coreReasonCode } };
    }
    return { status: 404, body: null };
  };
}

function fakeDockerPs({ restartPolicy = "always" } = {}) {
  return async () => ({
    code: 0,
    stdout: [
      JSON.stringify({ Names: "nexualpha-web-blue", Status: "Up 2 hours", RestartPolicy: restartPolicy }),
      JSON.stringify({ Names: "nexualpha-web-green-rollback", Status: "Exited (0) 1 hour ago", RestartPolicy: "unless-stopped" }),
      "",
    ].join("\n"),
    stderr: "",
  });
}

function fakeStatfs() {
  return async () => ({ bsize: 4096, blocks: 10_000_000, bavail: 2_000_000 });
}
