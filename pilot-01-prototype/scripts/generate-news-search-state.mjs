#!/usr/bin/env node
// Compiles the reversible T10 list (ops/newsroom/thin-noindex-*.json, newest file wins) into
// src/data/news-search-state.generated.js, the only copy the site, the Worker and the sitemap/SEO scripts read.
//   node scripts/generate-news-search-state.mjs [--check]
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const listDir = path.resolve(projectRoot, "../ops/newsroom");
const outPath = path.join(projectRoot, "src/data/news-search-state.generated.js");

export function renderNewsSearchStateModule(list, sourceName) {
  const thin = [...new Set((list.noindex || []).map((row) => row.slug))].sort();
  const canonical = Object.fromEntries((list.canonical || []).map((row) => [row.slug, row.canonicalSlug]).sort(([a], [b]) => a.localeCompare(b)));
  const strong = (list.strong || []).map((row) => row.slug);
  return [
    `// Generated by scripts/generate-news-search-state.mjs from ops/newsroom/${sourceName}. Do not edit by hand.`,
    "// T10 indexation recovery: thin template pages served noindex,follow and kept out of sitemaps; weaker duplicates",
    "// carrying rel=canonical to the stronger article; the strongest articles by Google impressions (internal-link priority).",
    `export const NEWS_SEARCH_STATE_SOURCE = ${JSON.stringify(sourceName)};`,
    `export const NEWS_THIN_NOINDEX_SLUGS = Object.freeze(${JSON.stringify(thin)});`,
    `export const NEWS_CANONICAL_TARGETS = Object.freeze(${JSON.stringify(canonical)});`,
    `export const NEWS_STRONG_SLUGS = Object.freeze(${JSON.stringify(strong)});`,
    "",
  ].join("\n");
}

export function latestListName(dir = listDir) {
  const files = readdirSync(dir).filter((name) => /^thin-noindex-\d{4}-\d{2}-\d{2}\.json$/.test(name)).sort();
  if (!files.length) throw new Error(`no thin-noindex list in ${dir}`);
  return files.at(-1);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const name = latestListName();
  const text = renderNewsSearchStateModule(JSON.parse(readFileSync(path.join(listDir, name), "utf8")), name);
  if (process.argv.includes("--check")) {
    if (readFileSync(outPath, "utf8") !== text) { console.error("news-search-state.generated.js is stale: run node scripts/generate-news-search-state.mjs"); process.exit(1); }
    console.log("news-search-state.generated.js is current");
  } else {
    writeFileSync(outPath, text);
    console.log(`wrote ${path.relative(projectRoot, outPath)} from ${name}`);
  }
}
