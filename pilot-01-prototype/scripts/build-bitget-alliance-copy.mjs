// Builds src/data/bitget-alliance-copy.js from content-source/bitget-alliance/<locale>.json (the written editions of
// /activities/bitget-alliance). Run after editing a locale file: node scripts/build-bitget-alliance-copy.mjs
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = path.join(root, "content-source", "bitget-alliance");
const target = path.join(root, "src", "data", "bitget-alliance-copy.js");
const en = JSON.parse(readFileSync(path.join(source, "en.json"), "utf8"));

const shape = (value) => (Array.isArray(value) ? value.map(shape) : value && typeof value === "object" ? Object.fromEntries(Object.entries(value).map(([k, v]) => [k, shape(v)])) : typeof value);
const enShape = JSON.stringify(shape(en));
const copy = {};
for (const file of readdirSync(source).filter((name) => name.endsWith(".json")).sort()) {
  const locale = file.replace(/\.json$/, "");
  const data = JSON.parse(readFileSync(path.join(source, file), "utf8"));
  if (JSON.stringify(shape(data)) !== enShape) throw new Error(`${file}: structure differs from en.json`);
  copy[locale] = data;
}
const body = `// Generated by scripts/build-bitget-alliance-copy.mjs from content-source/bitget-alliance/*.json — do not edit by hand.
// Page copy of /activities/bitget-alliance (route chunk route-campaign-bitget). Numbers match English.
export const BITGET_ALLIANCE_COPY = Object.freeze(${JSON.stringify(copy, null, 1)});
`;
writeFileSync(target, body);
console.log(`bitget-alliance copy: ${Object.keys(copy).join(", ")}`);
