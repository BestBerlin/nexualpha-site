import { readFile, writeFile } from "node:fs/promises";
import { v2Copy } from "../src/content/v2-copy.js";
import { V2_SHELL_COPY_LOCALES } from "./generate-v2-shell-copy.mjs";

const file = new URL("../src/content/v2-route-copy.js", import.meta.url);
const source = await readFile(file, "utf8");
const helpers = source.slice(source.indexOf("function localeFallback"));
const rows = Object.fromEntries(V2_SHELL_COPY_LOCALES.map((locale) => {
  const copy = v2Copy(locale);
  return [locale, {
    decisionWorkbench: { discovered: copy.decisionWorkbench.discovered, openOfficial: copy.decisionWorkbench.openOfficial },
    assetCapabilityNone: copy.assetCapabilities.none,
    common: Object.fromEntries(["verifiedSource", "feeSignal", "regionAvailability", "dimension"].map((key) => [key, copy.common[key]])),
  }];
}));
await writeFile(file, "// Generated by scripts/generate-v2-route-copy.mjs from v2-copy.js.\n"
  + `const V2_ROUTE_COPY = Object.freeze(${JSON.stringify(rows, null, 2).replace(/</g, "\\u003c")});\n\n` + helpers);
