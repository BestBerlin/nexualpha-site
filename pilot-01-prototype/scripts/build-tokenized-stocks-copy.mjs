// Builds the tokenized-stocks copy modules from content-source/tokenized-stocks/<locale>.json:
// - src/data/tokenized-stocks-copy.js      full page copy (hub + ticker pages; route chunk route-tokenized-stocks)
// - src/data/tokenized-stocks-teaser.js    the few strings of the home strip and the exchange-profile block
// - src/data/tokenized-stocks-labels.js    the header/footer label (browser entry: one short string per locale)
// Run after editing a locale file: node scripts/build-tokenized-stocks-copy.mjs
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { TS_EXCHANGES } from "../src/data/tokenized-stocks-facts.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = path.join(root, "content-source", "tokenized-stocks");
const en = JSON.parse(readFileSync(path.join(source, "en.json"), "utf8"));

// Same keys as English (arrays may differ in length: the tr edition cites other sources).
const keysOf = (value) => (Array.isArray(value) ? "[]" : value && typeof value === "object" ? Object.fromEntries(Object.keys(value).sort().map((k) => [k, keysOf(value[k])])) : typeof value);
const placeholders = (value) => (typeof value === "string" ? [...value.matchAll(/\{(\w+)\}/g)].map((m) => m[1]).sort().join(",") : null);
function checkPlaceholders(a, b, where) {
  if (typeof a === "string") { if (placeholders(a) !== placeholders(b)) throw new Error(`${where}: placeholders differ`); return; }
  if (a && typeof a === "object" && !Array.isArray(a)) for (const key of Object.keys(a)) checkPlaceholders(a[key], b[key], `${where}.${key}`);
}
// Region names of the "not available in" column, resolved once here (Node ICU) so SSR and the browser print the same text.
const REGION_CODES = [...new Set(TS_EXCHANGES.flatMap((ex) => ex.excluded?.v || []))].sort();
const MAINLAND = { en: "Mainland China", "zh-Hans": "中国大陆", "zh-Hant": "中國大陸" };
function regionNames(locale) {
  const names = new Intl.DisplayNames([locale], { type: "region" });
  return Object.fromEntries(REGION_CODES.map((code) => [code, code === "CN" && MAINLAND[locale] ? MAINLAND[locale] : names.of(code)]));
}
const copy = {};
for (const file of readdirSync(source).filter((name) => name.endsWith(".json")).sort()) {
  const locale = file.replace(/\.json$/, "");
  const data = JSON.parse(readFileSync(path.join(source, file), "utf8"));
  if (JSON.stringify(keysOf(data)) !== JSON.stringify(keysOf(en))) throw new Error(`${file}: keys differ from en.json`);
  checkPlaceholders(en, data, locale);
  const values = (value) => (value && typeof value === "object" ? Object.values(value).flatMap(values) : [String(value)]);
  if (locale === "tr" && values(data).some((text) => /bitget/i.test(text))) throw new Error("tr.json must not name Bitget");
  copy[locale] = { ...data, regions: regionNames(locale), locale };
}
const TEASER_KEYS = ["homeKicker", "homeTitle", "homeBody", "homeAll", "homeTickers", "venueH", "venueLink", "lanes", "hours", "levUpTo", "listed", "breadcrumb", "source", "cols", "names", "mx", "cta"];
const teaser = Object.fromEntries(Object.entries(copy).map(([locale, data]) => [locale, Object.fromEntries(TEASER_KEYS.map((key) => [key, data[key]]))]));
const labels = Object.fromEntries(Object.entries(copy).map(([locale, data]) => [locale, data.breadcrumb]));
const head = "// Generated by scripts/build-tokenized-stocks-copy.mjs from content-source/tokenized-stocks/*.json — do not edit by hand.\n";
writeFileSync(path.join(root, "src", "data", "tokenized-stocks-copy.js"), `${head}// Page copy of every edition: SERVER ONLY (Worker head, SSR, sitemap). The browser loads one edition from
// src/data/tokenized-stocks-copy/<locale>.js (tokenized-stocks-copy-client.js).\nexport const TS_COPY = Object.freeze(${JSON.stringify(copy, null, 1)});\n`);
// One module per locale for the browser (2026-10-19): a page ships only its own edition (prerender state "tsPage" on
// SSR pages, a lazy chunk after a client-side navigation). tokenized-stocks-copy.js above stays server-only.
const localeDir = path.join(root, "src", "data", "tokenized-stocks-copy");
mkdirSync(localeDir, { recursive: true });
for (const file of readdirSync(localeDir)) if (file.endsWith(".js")) rmSync(path.join(localeDir, file));
for (const [locale, data] of Object.entries(copy)) {
  writeFileSync(path.join(localeDir, `${locale.toLowerCase()}.js`), `${head}// ${locale} edition of the tokenized-stocks page copy (browser: lazy chunk; SSR: tokenized-stocks-copy.js).\nexport const TS_COPY_LOCALE = Object.freeze(${JSON.stringify({ ...data, locale })});\n`);
}
writeFileSync(path.join(root, "src", "data", "tokenized-stocks-teaser.js"), `${head}// Home strip and exchange-profile block strings (lazy chunks only).\nexport const TS_TEASER = Object.freeze(${JSON.stringify(teaser)});\n`);
writeFileSync(path.join(root, "src", "data", "tokenized-stocks-labels.js"), `${head}// Header and footer label of the tokenized-stocks hub (browser entry).\nexport const TS_NAV_LABELS = Object.freeze(${JSON.stringify(labels)});\n`);
console.log(`tokenized-stocks copy: ${Object.keys(copy).join(", ")}`);
