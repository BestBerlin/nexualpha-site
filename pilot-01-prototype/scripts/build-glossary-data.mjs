#!/usr/bin/env node
// Compiles the crypto glossary (2026-10-13) from content-source/glossary/<locale>.json and the term index
// (src/data/glossary-terms.js) into the modules the site loads:
//   src/data/glossary-index-<locale>.js       hub list
//   src/data/glossary-shard-<locale>-<n>.js   term pages (denormalized: related names, lesson title, coin name, cross-links)
//   src/data/glossary-links-<locale>.js       auto-link forms for news articles and academy transcripts
//   src/data/glossary-content-all.js          every locale for the server (head, JSON-LD, sitemap)
// A locale or term without written content falls back to English and is marked (served noindex,follow).
// Usage: node scripts/build-glossary-data.mjs [--merge-parts]   (--merge-parts first merges writer part files from
// content-source/glossary/_parts/<locale>.*.json into content-source/glossary/<locale>.json)
import { existsSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { GLOSSARY_TERMS, glossaryTermBySlug } from "../src/data/glossary-terms.js";
import { GLOSSARY_INDEX_LOCALES, GLOSSARY_SHARDS, glossaryShard } from "../src/data/glossary-routes.js";
import { createGlossaryLinker } from "../src/data/glossary-autolink.js";
import { validateFile } from "./validate-glossary-content.mjs";
import { ACADEMY_CONTENT_BY_LOCALE } from "../src/data/academy-content-all.js";
import { ACADEMY_EPISODES } from "../src/data/academy-season1.js";
import { COIN_ROWS } from "../src/data/coins-data.generated.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceDir = path.join(root, "content-source", "glossary");
const partsDir = path.join(sourceDir, "_parts");
const dataDir = path.join(root, "src", "data");
const fileLocale = (locale) => locale.toLowerCase();
const HEADER = "// Generated by scripts/build-glossary-data.mjs from content-source/glossary. Do not edit by hand.\n";

if (process.argv.includes("--merge-parts") && existsSync(partsDir)) {
  for (const locale of GLOSSARY_INDEX_LOCALES) {
    const files = readdirSync(partsDir).filter((name) => name.startsWith(`${locale}.`) && name.endsWith(".json")).sort();
    if (!files.length) continue;
    const merged = {};
    for (const name of files) Object.assign(merged, JSON.parse(readFileSync(path.join(partsDir, name), "utf8")).terms || {});
    const target = path.join(sourceDir, `${locale}.json`);
    const existing = existsSync(target) ? JSON.parse(readFileSync(target, "utf8")).terms || {} : {};
    const all = { ...existing, ...merged };
    const terms = Object.fromEntries(GLOSSARY_TERMS.filter((t) => all[t.slug]).map((t) => [t.slug, all[t.slug]]));
    writeFileSync(target, `${JSON.stringify({ locale, terms }, null, 1)}\n`);
    console.log(`merged ${files.length} part files -> ${locale}.json (${Object.keys(terms).length} terms)`);
  }
}

// ---------------------------------------------------------------- load + validate
const content = {};
for (const locale of GLOSSARY_INDEX_LOCALES) {
  const file = path.join(sourceDir, `${locale}.json`);
  if (!existsSync(file)) { content[locale] = {}; console.warn(`glossary: no ${locale}.json (English fallback)`); continue; }
  const json = JSON.parse(readFileSync(file, "utf8"));
  const errors = validateFile(json);
  if (errors.length) { console.error(errors.join("\n")); throw new Error(`glossary: ${locale}.json has ${errors.length} validation errors`); }
  content[locale] = json.terms;
}
const EN = content.en;
const missingEn = GLOSSARY_TERMS.filter((t) => !EN[t.slug]).map((t) => t.slug);
if (missingEn.length && !process.argv.includes("--allow-missing")) throw new Error(`glossary: English entries missing: ${missingEn.join(", ")}`);

// ---------------------------------------------------------------- helpers
const entryFor = (locale, slug) => {
  if (content[locale]?.[slug]) return { entry: content[locale][slug], contentLocale: locale };
  if (EN[slug]) return { entry: EN[slug], contentLocale: "en" };
  return null;
};
// Auto-link surface forms of a term in a locale: the name, the name without its bracketed part, the bracketed part and
// the "also called" names. Forms shared by two terms are dropped (ambiguous), except a term's own base name.
const STOP = new Set(["sợ hãi", "bất an", "approval", "allowance", "market price", "crypto exchange", "coin", "token", "tokens", "coins", "crypto", "margin", "order", "wallet", "exchange", "fee", "fees", "price", "bot", "pool", "rate"]);
function surfaceForms(entry) {
  const forms = new Set();
  const add = (value, primary = false) => {
    const form = String(value || "").trim().replace(/[.。]$/, "");
    if (!form) return;
    const cjk = /[぀-ヿ㐀-鿿가-힯]/.test(form);
    if (cjk ? form.length < 2 : form.length < 3) return;
    if (!primary && STOP.has(form.toLowerCase())) return;
    if (form.length > 40) return;
    // Secondary names must be specific enough to link inside news text: a phrase, an acronym or a long single word
    // ("spot", "volume", "chain", "stake" are not).
    if (!primary) {
      const acronym = /^[A-Za-z0-9/&-]{3,8}$/.test(form) && (form.match(/[A-Z]/g) || []).length >= 2;
      const phrase = /[\s-]/.test(form) && form.length >= 6;
      if (cjk ? form.length < 3 : !(acronym || phrase || form.length >= 8)) return;
    }
    forms.add(form);
  };
  const term = String(entry.term || "");
  const base = term.replace(/\s*[（(][^）)]*[）)]\s*/g, " ").replace(/\s+/g, " ").trim();
  add(base, true);
  for (const inner of term.matchAll(/[（(]([^）)]+)[）)]/g)) for (const part of inner[1].split(/[,，/、]/)) add(part);
  if (base !== term) add(term);
  for (const aka of entry.aka || []) add(aka);
  return [...forms];
}
function linkForms(locale) {
  const rows = GLOSSARY_TERMS.map((t) => [t.slug, surfaceForms(entryFor(locale, t.slug).entry)]);
  const owners = new Map();
  for (const [slug, forms] of rows) for (const form of forms) {
    const key = form.toLowerCase();
    owners.set(key, [...(owners.get(key) || []), slug]);
  }
  return rows.map(([slug, forms], index) => [slug, forms.filter((form, i) => (owners.get(form.toLowerCase()) || []).length === 1 || i === 0)]);
}
const lessonOf = (locale, id) => {
  const episode = ACADEMY_EPISODES.find((e) => e.id === id);
  if (!episode) return null;
  const lessons = (ACADEMY_CONTENT_BY_LOCALE[locale] || ACADEMY_CONTENT_BY_LOCALE.en).lessons;
  return { id, slug: episode.slug, ep: episode.ep, title: lessons[episode.ep - 1]?.title || ACADEMY_CONTENT_BY_LOCALE.en.lessons[episode.ep - 1].title };
};
const COIN_BY_SLUG = new Map(COIN_ROWS.map((row) => [row[1], { slug: row[1], name: row[2], symbol: row[3] }]));
const segment = (parts) => parts.map((part) => (typeof part === "string" ? part : [part.text, part.slug]));
const compactSegments = (parts) => (parts.length === 1 && typeof parts[0] === "string" ? parts[0] : segment(parts));

// ---------------------------------------------------------------- build per locale
const all = {};
const written = [];
for (const locale of GLOSSARY_INDEX_LOCALES) {
  const links = linkForms(locale);
  const index = [];
  const shards = Array.from({ length: GLOSSARY_SHARDS }, () => ({}));
  for (const term of GLOSSARY_TERMS) {
    const { entry, contentLocale } = entryFor(locale, term.slug);
    const linker = createGlossaryLinker(links, { max: 6, exclude: [term.slug] });
    const body = entry.body.map((paragraph) => compactSegments(linker.linkText(paragraph)));
    const example = compactSegments(linker.linkText(entry.example));
    const related = term.related.map((slug) => { const r = entryFor(locale, slug); return [slug, r.entry.term, r.entry.short]; });
    const page = {
      slug: term.slug, cat: term.cat, en: term.en, contentLocale,
      term: entry.term, aka: entry.aka, short: entry.short, body, example, mistakes: entry.mistakes, faq: entry.faq,
      title: entry.title, description: entry.description, related,
      lesson: term.lesson ? lessonOf(contentLocale, term.lesson) : null,
      coin: term.coin ? COIN_BY_SLUG.get(term.coin) || null : null,
      tool: term.tool, cta: term.cta,
    };
    shards[glossaryShard(term.slug)][term.slug] = page;
    index.push([term.slug, entry.term, entry.short, term.cat, contentLocale === locale ? 1 : 0]);
  }
  const collator = new Intl.Collator(locale, { sensitivity: "base" });
  index.sort((a, b) => collator.compare(a[1], b[1]));
  all[locale] = { shards, index, links };
  const loc = fileLocale(locale);
  writeFileSync(path.join(dataDir, `glossary-index-${loc}.js`), `${HEADER}// [slug, name, one-line definition, category, written in this locale (1) or English fallback (0)], sorted by name.\nexport const GLOSSARY_INDEX = Object.freeze(${JSON.stringify({ locale, terms: index })});\n`);
  shards.forEach((shard, n) => writeFileSync(path.join(dataDir, `glossary-shard-${loc}-${n}.js`), `${HEADER}export const GLOSSARY_SHARD = Object.freeze(${JSON.stringify(shard)});\n`));
  writeFileSync(path.join(dataDir, `glossary-links-${loc}.js`), `${HEADER}// [slug, [surface forms]] for auto-linking (src/data/glossary-autolink.js).\nexport const GLOSSARY_LINKS = Object.freeze(${JSON.stringify(links)});\n`);
  written.push(`${locale}: ${Object.keys(content[locale]).length}/${GLOSSARY_TERMS.length} written`);
}

// Server bundle: every locale's shards and index.
const imports = [];
const rows = [];
for (const locale of GLOSSARY_INDEX_LOCALES) {
  const loc = fileLocale(locale);
  const id = loc.replace(/-/g, "_");
  imports.push(`import { GLOSSARY_INDEX as I_${id} } from "./glossary-index-${loc}.js";`);
  const shardIds = [];
  for (let n = 0; n < GLOSSARY_SHARDS; n += 1) { imports.push(`import { GLOSSARY_SHARD as S_${id}_${n} } from "./glossary-shard-${loc}-${n}.js";`); shardIds.push(`S_${id}_${n}`); }
  rows.push(`  ${JSON.stringify(locale)}: { index: I_${id}, terms: Object.freeze(Object.assign({}, ${shardIds.join(", ")})) },`);
}
writeFileSync(path.join(dataDir, "glossary-content-all.js"), `${HEADER}// Server only (Worker head, JSON-LD, sitemap): never import from the browser.\n${imports.join("\n")}\nexport const GLOSSARY_CONTENT_BY_LOCALE = Object.freeze({\n${rows.join("\n")}\n});\n`);

// Remove generated modules of locales that are no longer built.
for (const name of readdirSync(dataDir)) {
  const match = name.match(/^glossary-(?:index|links|shard)-([a-z-]+?)(?:-\d+)?\.js$/);
  if (match && !GLOSSARY_INDEX_LOCALES.map(fileLocale).includes(match[1])) rmSync(path.join(dataDir, name));
}
console.log(`glossary: ${GLOSSARY_TERMS.length} terms; ${written.join("; ")}`);
if (!glossaryTermBySlug("funding-rate")) throw new Error("glossary: term index broken");
