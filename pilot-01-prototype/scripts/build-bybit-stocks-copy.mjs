// Builds src/data/bybit-stocks-copy.js from content-source/bybit-stocks/<locale>.json (the written editions of
// /activities/bybit-stocks). Run after editing a locale file: node scripts/build-bybit-stocks-copy.mjs
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = path.join(root, "content-source", "bybit-stocks");
const target = path.join(root, "src", "data", "bybit-stocks-copy.js");
const en = JSON.parse(readFileSync(path.join(source, "en.json"), "utf8"));

const shape = (value) => (Array.isArray(value) ? value.map(shape) : value && typeof value === "object" ? Object.fromEntries(Object.entries(value).map(([k, v]) => [k, shape(v)])) : typeof value);
const enShape = JSON.stringify(shape(en));
const copy = {};
for (const file of readdirSync(source).filter((name) => name.endsWith(".json")).sort()) {
  const locale = file.replace(/\.json$/, "");
  const data = JSON.parse(readFileSync(path.join(source, file), "utf8"));
  if (JSON.stringify(shape(data)) !== enShape) throw new Error(`${file}: structure differs from en.json`);
  copy[locale] = data;
}
const body = `// Generated by scripts/build-bybit-stocks-copy.mjs from content-source/bybit-stocks/*.json — do not edit by hand.
// Page copy of /activities/bybit-stocks (route chunk route-campaign-bybit). Numbers and tickers match English.
export const BYBIT_STOCKS_COPY = Object.freeze(${JSON.stringify(copy, null, 1)});
`;
writeFileSync(target, body);
console.log(`bybit-stocks copy: ${Object.keys(copy).join(", ")}`);
