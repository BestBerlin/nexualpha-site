import { writeFile } from "node:fs/promises";
import { matrixCopy } from "../src/components/v3/exchange-matrix-copy.js";
import { costBasisCopy } from "../src/data/cost-basis-copy.js";
import { supportedLocales } from "../src/content/locale-manifest.ts";

const rows = Object.fromEntries(supportedLocales.map((locale) => [locale,
  Object.fromEntries(["all", "maker", "perp", "spot", "unchecked"].map((key) => [key, matrixCopy(locale)[key]]))]));
const rebates = Object.fromEntries(supportedLocales.map((locale) => [locale, costBasisCopy(locale).rebate]));
await writeFile(new URL("../src/data/rates-matrix-copy.js", import.meta.url),
  "// Generated by scripts/generate-rates-copy.mjs from exchange-matrix-copy.js.\n"
  + `const rows = ${JSON.stringify(rows).replace(/</g, "\\u003c")};\n`
  + `const rebates = ${JSON.stringify(rebates).replace(/</g, "\\u003c")};\n`
  + 'export const costBasisCopy = (locale = "en") => { const key = locale === "zh-CN" ? "zh-Hans" : locale === "zh-TW" ? "zh-Hant" : locale; return { rebate: rebates[key] || rebates[String(key).split("-")[0]] || rebates.en }; };\n'
  + 'export const matrixCopy = (locale = "en") => rows[locale === "zh-CN" ? "zh-Hans" : locale === "zh-TW" ? "zh-Hant" : locale] || (String(locale).toLowerCase().startsWith("pt") ? rows["pt-BR"] : rows[String(locale).split("-")[0]]) || rows.en;\n');
