import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import { venueDecisionContent } from "../src/data/venue-decision-content.js";

export function buildVenueDecisionSummary() {
  return Object.fromEntries(Object.keys(venueDecisionContent).map((slug) => [slug, true]));
}

export async function writeVenueDecisionSummary(outputUrl = new URL("../src/data/venue-decision-summary.js", import.meta.url)) {
  const summary = buildVenueDecisionSummary();
  const source = `// Generated by scripts/generate-venue-decision-summary.mjs from src/data/venue-decision-content.js.\n// Keep this route projection to reviewed slugs only; full editorial copy stays with venue detail routes.\n\nexport const venueDecisionSummary = Object.freeze(${JSON.stringify(summary, null, 2)});\n\nexport const hasVenueDecisionSummary = (slug) => Boolean(venueDecisionSummary[slug]);\n`;
  await writeFile(outputUrl, source);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await writeVenueDecisionSummary();
