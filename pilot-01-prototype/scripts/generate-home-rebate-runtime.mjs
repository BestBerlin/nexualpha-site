import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import {
  HOME_AUTO_SETTLE,
  HOME_PARTNERS,
  HOME_PUSH,
  HOME_REBATE_MAX_PCT,
  HOME_REBATE_SHARE,
  HOME_SETTLE,
} from "../src/data/home-rebate-tiers.js";

export function buildHomeRebateRuntimeSnapshot() {
  return {
    maxPct: HOME_REBATE_MAX_PCT,
    share: Object.fromEntries(Object.entries(HOME_REBATE_SHARE)),
    partners: [...HOME_PARTNERS],
    push: [...HOME_PUSH],
    autoSettle: [...HOME_AUTO_SETTLE],
    settle: Object.fromEntries(Object.entries(HOME_SETTLE)),
  };
}

function serialize(value) {
  return JSON.stringify(value).replace(/</g, "\\u003c");
}

export function renderHomeRebateRuntime(snapshot = buildHomeRebateRuntimeSnapshot()) {
  return `// Generated by scripts/generate-home-rebate-runtime.mjs from src/data/home-rebate-tiers.js.\n// Keep this runtime projection free of partner-registry imports; regenerate after referral partner data changes.\nimport { partnerPromotionGate } from "./partner-geo-policy.js";\n\nexport const HOME_REBATE_MAX_PCT = ${JSON.stringify(snapshot.maxPct)};\nexport const HOME_REBATE_SHARE = Object.freeze(${serialize(snapshot.share)});\nexport const HOME_PARTNERS = Object.freeze(${serialize(snapshot.partners)});\nexport const HOME_PUSH = Object.freeze(${serialize(snapshot.push)});\nexport const HOME_AUTO_SETTLE = Object.freeze(${serialize(snapshot.autoSettle)});\nexport const HOME_SETTLE = Object.freeze(${serialize(snapshot.settle)});\n\nconst turkeyGated = (slug, locale, market) => partnerPromotionGate(slug, {\n  locale,\n  market: /^tr(?:-|$)/i.test(String(locale || "")) ? "TR" : market,\n})?.country === "TR";\nexport const homePartnersFor = (locale, market) => HOME_PARTNERS.filter((slug) => !turkeyGated(slug, locale, market));\nexport const homePushFor = (locale, market) => HOME_PUSH.filter((slug) => !turkeyGated(slug, locale, market));\nexport function homeRebateMaxPctFor(locale, market) {\n  const shares = homePartnersFor(locale, market).map((slug) => HOME_REBATE_SHARE[slug] ?? 0);\n  return shares.length ? Math.round(Math.max(...shares) * 100) : HOME_REBATE_MAX_PCT;\n}\n`;
}

export async function writeHomeRebateRuntimeFile(outputUrl = new URL("../src/data/home-rebate-runtime.js", import.meta.url)) {
  await writeFile(outputUrl, renderHomeRebateRuntime());
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeHomeRebateRuntimeFile();
}
