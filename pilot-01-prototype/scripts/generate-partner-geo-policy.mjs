#!/usr/bin/env node
import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { PARTNER_GEO_RESTRICTIONS, PARTNER_TERRITORIAL_RESTRICTIONS, JURISDICTION_PROMOTION_BANS, TURKEY_PROMOTED_PARTNERS, COUNTRY_BY_LOCALE, COUNTRY_BY_MARKET } from '../src/data/partner-geo-restrictions.js';
export function renderPartnerGeoPolicy() {
  const data = {
    PARTNER_RESTRICTED_COUNTRIES: Object.fromEntries(Object.entries(PARTNER_GEO_RESTRICTIONS).map(([slug, rows]) => [slug, rows.map(row => row.country)])),
    PARTNER_RESTRICTED_SCOPES: Object.fromEntries(Object.entries(PARTNER_TERRITORIAL_RESTRICTIONS).map(([slug, rows]) => [slug, rows.map(row => row.scope)])),
    PROMOTION_BANNED_COUNTRIES: JURISDICTION_PROMOTION_BANS.map(row => row.country),
    TURKEY_PROMOTED_PARTNERS, COUNTRY_BY_LOCALE, COUNTRY_BY_MARKET,
  };
  return '// Generated by scripts/generate-partner-geo-policy.mjs. Edit partner-geo-restrictions.js instead.\n' + Object.entries(data).map(([key,value]) => `export const ${key} = Object.freeze(${JSON.stringify(value)});`).join('\n') + '\n';
}
if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(new URL('../src/data/partner-geo-policy.generated.js', import.meta.url), renderPartnerGeoPolicy());
}
