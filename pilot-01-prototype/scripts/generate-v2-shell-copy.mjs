export const V2_SHELL_COPY_ROOTS = [...new Set(V2_SHELL_COPY_PATHS.map((path) => path.split(".")[0]))];

function readPath(value, path) {
  return path.split(".").reduce((current, key) => current?.[key], value);
}

function writePath(target, path, value) {
  const keys = path.split(".");
  let current = target;
  for (const key of keys.slice(0, -1)) current = current[key] ||= {};
  current[keys.at(-1)] = value;
}

export function copyV2ShellValue(value) {
  if (typeof value === "string") return value;
  return undefined;
}

export function projectV2ShellCopy(full) {
  const projected = {};
  for (const path of V2_SHELL_COPY_PATHS) {
    const value = copyV2ShellValue(readPath(full, path));
    if (value !== undefined) writePath(projected, path, value);
  }
  return projected;
}

export function buildV2ShellCopySnapshot() {
  return Object.fromEntries(V2_SHELL_COPY_LOCALES.map((locale) => [locale, projectV2ShellCopy(v2Copy(locale))]));
}

function serialize(value) {
  return JSON.stringify(value, null, 2).replace(/</g, "\\u003c");
}

export async function writeV2ShellCopyFile(outputUrl = new URL("../src/content/v2-shell-copy.js", import.meta.url)) {
  const snapshot = buildV2ShellCopySnapshot();
  const file = `// Generated by scripts/generate-v2-shell-copy.mjs from src/content/v2-copy.js.\n// Keep this as a plain-string projection so the app shell does not import the full route copy graph.\n\nconst LOCALIZED = Object.freeze(${serialize(snapshot)});\n\nconst intlMap = { "zh-Hans": "zh-CN", "zh-Hant": "zh-TW", "pt-BR": "pt-BR", ur: "ur", uk: "uk" };\nexport const intlLocale = (locale) => intlMap[locale] ?? locale;\n\nfunction text(locale) {\n  return LOCALIZED[locale] || LOCALIZED[String(locale || "").split(/[-_]/)[0]] || LOCALIZED.en;\n}\n\nexport function v2ShellCopy(locale = "en") {\n  return text(locale);\n}\n`;
  await writeFile(outputUrl, file);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeV2ShellCopyFile();
}
