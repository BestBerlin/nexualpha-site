#!/usr/bin/env node
// Writes src/data/referral-partners.generated.js: the partner facts the search titles need (name, invite code,
// rebate share, payout cadence), taken from the partner feed. The production server ships only a few src/data files,
// so referral-seo.js reads this small standalone module instead of the whole CTA graph.
// tests/referral-seo.test.mjs fails if this file drifts from the partner feed.
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { buildPartnersFeed } from "../src/data/partners-feed.js";

export function referralPartnerRows() {
  return buildPartnersFeed({ generatedAt: "static" }).partners
    .filter((p) => p.inviteCode)
    .map(({ slug, name, inviteCode, share, settle, termsConfirmedOn }) => ({ slug, name, inviteCode, share, settle, termsConfirmedOn }));
}

export function renderReferralPartners(rows = referralPartnerRows()) {
  return `// Generated by scripts/generate-referral-partners.mjs from the partner feed. Do not edit by hand.\nexport const REFERRAL_PARTNERS = Object.freeze(${JSON.stringify(rows, null, 2)});\n`;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  writeFileSync(path.join(root, "src/data/referral-partners.generated.js"), renderReferralPartners());
  console.log("referral-partners.generated.js written");
}
