export function appDownloadCopy(locale = "en") {
  const raw = String(locale || "en");
  if (raw === "zh-Hant" || raw === "zh-TW" || raw === "zh-HK") return APP_DOWNLOAD_COPY["zh-Hant"];
  if (raw === "zh-Hans" || raw === "zh-CN" || raw === "zh-SG" || raw === "zh") return APP_DOWNLOAD_COPY["zh-Hans"];
  if (raw.toLowerCase() === "pt-br" || raw.toLowerCase() === "pt") return APP_DOWNLOAD_COPY["pt-BR"];
  const base = raw.split("-")[0];
  return APP_DOWNLOAD_COPY[raw] || APP_DOWNLOAD_COPY[base] || APP_DOWNLOAD_COPY.en;
}
