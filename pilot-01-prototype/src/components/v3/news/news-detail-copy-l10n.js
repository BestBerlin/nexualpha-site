// Fills the keys each locale object of `copy` still inherits from English; keys defined inline win.
export function mergeNewsDetailCopy(copy) {
  for (const [locale, strings] of Object.entries(NEWS_DETAIL_COPY_L10N)) {
    const target = copy[locale];
    if (!target) continue;
    for (const [key, value] of Object.entries(strings)) {
      if (target[key] === undefined || target[key] === copy.en?.[key]) target[key] = value;
    }
  }
  return copy;
}
